-- Run once in Supabase SQL Editor. Creates a private gig-history table.
create table if not exists public.user_gigs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  artist_id text not null,
  artist_name text not null,
  venue text not null,
  city text not null default '',
  country text not null default '',
  event_date date not null,
  tour text not null default '',
  notes text not null default '',
  source text not null default 'manual',
  source_id text not null default '',
  source_url text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists user_gigs_user_date_idx on public.user_gigs(user_id, event_date desc);
alter table public.user_gigs enable row level security;
drop policy if exists "Users can view their own gigs" on public.user_gigs;
create policy "Users can view their own gigs" on public.user_gigs for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users can add their own gigs" on public.user_gigs;
create policy "Users can add their own gigs" on public.user_gigs for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users can remove their own gigs" on public.user_gigs;
create policy "Users can remove their own gigs" on public.user_gigs for delete to authenticated using (auth.uid() = user_id);
grant usage on schema public to authenticated;
grant select, insert, delete on table public.user_gigs to authenticated;
grant usage, select on sequence public.user_gigs_id_seq to authenticated;
