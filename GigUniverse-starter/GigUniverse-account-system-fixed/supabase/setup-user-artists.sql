-- Run this once in Supabase: SQL Editor -> New query -> paste -> Run.
-- Each signed-in user can only read, add, or remove their own saved artists.

create table if not exists public.user_artists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  artist_id text not null,
  name text not null,
  artist_type text,
  country text,
  area text,
  disambiguation text not null default '',
  tags jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, artist_id)
);

alter table public.user_artists enable row level security;

drop policy if exists "Users can view their own artists" on public.user_artists;
create policy "Users can view their own artists"
  on public.user_artists for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can add their own artists" on public.user_artists;
create policy "Users can add their own artists"
  on public.user_artists for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can remove their own artists" on public.user_artists;
create policy "Users can remove their own artists"
  on public.user_artists for delete
  to authenticated
  using (auth.uid() = user_id);
